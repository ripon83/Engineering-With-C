/*
 * Program: If Statement Block 2
 * Purpose: Demonstrates the corresponding control-statement concept
 *          presented in Chapter 4.
 */

#include <stdio.h>
int main()  // Main function: program execution starts here
{
    int n = 1;

    if (n == 1)  // Test the specified condition
    {
        printf("It is very easy to defeat someone, "  // Display output
               "but it is very hard to win someone.\n");
        printf("We should learn how to respect others.\n");  // Display output
    }

    return 0;  // Indicate successful program termination
}

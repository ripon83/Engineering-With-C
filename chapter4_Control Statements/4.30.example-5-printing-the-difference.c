#include <stdio.h>

int main()  // Main function: program execution starts here
{
    double a = 0.1 + 0.2;
    double b = 0.3;

    printf("%.17f\n", a);  // Display output
    printf("%.17f\n", b);  // Display output

    return 0;  // Indicate successful program termination
}

#include <stdio.h>

int main()  // Main function: execution starts here
{
    int i;

    for (i = 0; i < 10; i--)  // Start or control a for loop
    {
        printf("%d\t", i);  // Display output
    }

    return 0;  // Indicate successful program termination
}
